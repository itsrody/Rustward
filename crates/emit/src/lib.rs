//! Deterministic, compiler-friendly list emission.

use anyhow::Result;
use model::{Config, CosmeticPayload, NetworkRule, Rule, RuleState};
use std::collections::BTreeMap;

#[derive(Debug, Clone)]
pub struct EmitResult {
    pub text: String,
    pub buckets: BTreeMap<String, usize>,
    pub rules: Vec<Rule>,
}

pub fn emit(rules: &[Rule], config: &Config, build_id: &str) -> Result<EmitResult> {
    let mut selected: Vec<Rule> = rules
        .iter()
        .filter(|rule| {
            !matches!(rule.state(), RuleState::Excluded(_))
                && matches!(rule.eligibility(), model::Eligibility::Eligible)
        })
        .cloned()
        .collect();
    selected.sort_by(|a, b| emit_key(a).cmp(&emit_key(b)));

    let mut buckets = BTreeMap::new();
    let mut sections: BTreeMap<u8, Vec<String>> = BTreeMap::new();
    for rule in &selected {
        let section = bucket(rule);
        *buckets
            .entry(section_name(section).to_string())
            .or_insert(0usize) += 1;
        let mut line = rule.text().trim().to_string();
        if config.output.inline_audit_comments {
            if let Rule::Network(network) = rule {
                if let RuleState::Rewritten(id) = &network.state {
                    line.push_str(&format!(" ! RustShield: rewrite={id}"));
                }
            }
        }
        sections.entry(section).or_default().push(line);
    }

    let mut output = String::new();
    output.push_str(&format!("! Title: {}\n", config.output.title));
    output.push_str(&format!(
        "! Last modified: {}\n",
        config.output.last_modified
    ));
    output.push_str(&format!("! Expires: {}\n", config.output.expires));
    output.push_str(&format!("! Description: {}\n", config.output.description));
    output.push_str("! RustShield: generated offline list\n");
    output.push_str(&format!("! RustShield: build-id={build_id}\n"));
    output.push_str(&format!(
        "! RustShield: emit-order={}\n",
        config.output.emit_order
    ));
    output.push_str(&format!("! RustShield: rules={}\n", selected.len()));
    output.push_str("! Generated by RustShield — do not edit\n");

    for section in 0..=13 {
        if let Some(lines) = sections.get(&section) {
            output.push('\n');
            for line in lines {
                output.push_str(line);
                output.push('\n');
            }
        }
    }

    Ok(EmitResult {
        text: output,
        buckets,
        rules: selected,
    })
}

fn bucket(rule: &Rule) -> u8 {
    match rule {
        Rule::Network(network) => {
            if network.is_badfilter {
                0
            } else if network.is_exception && network.is_generic_hide {
                1
            } else if network.is_exception {
                2
            } else if network.important {
                3
            } else if network.is_csp {
                4
            } else if network.is_redirect {
                5
            } else if network.is_removeparam {
                6
            } else if network.is_generic_hide {
                7
            } else if network.tag.is_some() {
                8
            } else {
                9
            }
        }
        Rule::Cosmetic(cosmetic) => match &cosmetic.payload {
            CosmeticPayload::NativeCss(_) if cosmetic.generic => 10,
            CosmeticPayload::NativeCss(_) => {
                if cosmetic.action == model::HideOrUnhide::Unhide {
                    12
                } else {
                    11
                }
            }
            CosmeticPayload::LightProcedural { .. } => {
                if cosmetic.action == model::HideOrUnhide::Unhide {
                    12
                } else {
                    12
                }
            }
            CosmeticPayload::VettedScriptlet { .. } => 13,
        },
    }
}

fn section_name(section: u8) -> &'static str {
    match section {
        0 => "badfilter",
        1 => "generichide_exception",
        2 => "exception",
        3 => "important",
        4 => "csp",
        5 => "redirect",
        6 => "removeparam",
        7 => "generic_hide",
        8 => "tagged",
        9 => "filter",
        10 => "generic_css",
        11 => "host_css",
        12 => "light_procedural_or_unhide",
        13 => "vetted_scriptlet",
        _ => "other",
    }
}

fn emit_key(rule: &Rule) -> (u8, u8, u32, u32, String, String, String, String) {
    match rule {
        Rule::Network(network) => (
            bucket(rule),
            index_class(network),
            network.mask,
            network.features,
            network.hostname.clone().unwrap_or_default(),
            network.body.clone(),
            network.domains.join("|"),
            format!(
                "{:?}|{}",
                network.modifier_option,
                network.modifier_option.clone().unwrap_or_default()
            ),
        ),
        Rule::Cosmetic(cosmetic) => (
            bucket(rule),
            0,
            0,
            0,
            cosmetic.hosts.join(","),
            cosmetic.payload_key(),
            cosmetic.selector_ops.join(","),
            cosmetic.text.clone(),
        ),
    }
}

fn index_class(rule: &NetworkRule) -> u8 {
    if rule.domains.len() == 1 && rule.not_domains.is_empty() {
        0
    } else if !rule.hostname.is_empty_or_absent() || !rule.body.is_empty() {
        1
    } else if rule.is_removeparam && !rule.body.is_empty() {
        2
    } else if rule.domains.len() > 1 {
        3
    } else if !rule.to_domains.is_empty() || !rule.not_to_domains.is_empty() {
        4
    } else {
        5
    }
}

trait OptionalStr {
    fn is_empty_or_absent(&self) -> bool;
}

impl OptionalStr for Option<String> {
    fn is_empty_or_absent(&self) -> bool {
        self.as_deref().is_none_or(str::is_empty)
    }
}

trait CosmeticPayloadKey {
    fn payload_key(&self) -> String;
}

impl CosmeticPayloadKey for model::CosmeticRule {
    fn payload_key(&self) -> String {
        serde_json::to_string(&self.payload).unwrap_or_else(|_| format!("{:?}", self.payload))
    }
}
